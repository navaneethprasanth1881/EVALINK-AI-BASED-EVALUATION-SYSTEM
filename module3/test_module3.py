# =========================================================
# FIND PREPROCESSED PDF
# =========================================================

def find_preprocessed_pdf():
    """
    Search the entire project for preprocessed.pdf
    generated by Module 2.
    """

    print()
    print("Searching for preprocessed.pdf...")

    pdf_files = list(
        PROJECT_ROOT.rglob("preprocessed.pdf")
    )

    if not pdf_files:
        raise FileNotFoundError(
            "preprocessed.pdf was not found.\n"
            "Make sure Module 2 generated the file."
        )

    # If multiple files are found, use the most recently modified one
    pdf_path = max(
        pdf_files,
        key=lambda file: file.stat().st_mtime
    )

    print(f"Found preprocessed PDF:")
    print(pdf_path)

    return pdf_path


