"""
Module 5 - JSON Validation

JSON Loader

Loads the OCR JSON generated by Module 4.

This module does NOT:
    - modify OCR text
    - correct OCR
    - validate the JSON structure
    - evaluate answers
"""

import json
import os

from config5 import JSONValidationConfig


class JSONLoader:

    # =========================================================
    # Constructor
    # =========================================================

    def __init__(self):

        self.input_folder = (
            JSONValidationConfig.INPUT_FOLDER
        )

        self.input_filename = (
            JSONValidationConfig.INPUT_FILENAME
        )

    # =========================================================
    # Get Input Path
    # =========================================================

    def get_input_path(self):

        """
        Build the path to Module 4's OCR JSON.
        """

        return os.path.join(

            self.input_folder,

            self.input_filename

        )

    # =========================================================
    # Check File
    # =========================================================

    def check_file(self, file_path):

        """
        Check whether the JSON file exists.
        """

        if not os.path.exists(file_path):

            raise FileNotFoundError(

                "OCR JSON file was not found:\n"
                f"{file_path}"

            )

        if not os.path.isfile(file_path):

            raise ValueError(

                "OCR JSON path is not a file:\n"
                f"{file_path}"

            )

    # =========================================================
    # Load JSON
    # =========================================================

    def load(self, file_path=None):

        """
        Load OCR JSON from disk.

        Returns
        -------
        dict
            Parsed JSON data.
        """

        if file_path is None:

            file_path = self.get_input_path()

        # -----------------------------------------------------
        # Check file
        # -----------------------------------------------------

        self.check_file(file_path)

        # -----------------------------------------------------
        # Open JSON
        # -----------------------------------------------------

        try:

            with open(

                file_path,

                "r",

                encoding="utf-8"

            ) as file:

                data = json.load(file)

        except json.JSONDecodeError as error:

            raise ValueError(

                "The OCR file contains invalid JSON:\n"
                f"{file_path}"

            ) from error

        except OSError as error:

            raise OSError(

                "Unable to read OCR JSON file:\n"
                f"{file_path}"

            ) from error

        # -----------------------------------------------------
        # Top-level type check
        # -----------------------------------------------------

        if not isinstance(data, dict):

            raise ValueError(

                "OCR JSON must contain a "
                "top-level JSON object."

            )

        return data

    # =========================================================
    # Load From Document
    # =========================================================

    def load_into_document(self, document):

        """
        Load OCR JSON and store it in the Document object.

        The loaded data is copied as-is.
        """

        data = self.load()

        document.ocr_json = data

        return document