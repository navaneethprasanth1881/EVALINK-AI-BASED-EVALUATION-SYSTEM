"""
Module 5 - JSON Validation

JSON Schema

Defines the expected structure of the OCR JSON
generated by Module 4.

This schema is used by the validation module.
It does NOT modify OCR content.
"""


class OCRSchema:

    # =========================================================
    # Student Information Schema
    # =========================================================

    STUDENT_SCHEMA = {

        "type": "object",

        "properties": {

            "student_name": {
                "type": ["string", "null"]
            },

            "register_number": {
                "type": ["string", "null"]
            },

            "roll_number": {
                "type": ["string", "null"]
            },

            "subject": {
                "type": ["string", "null"]
            },

            "course": {
                "type": ["string", "null"]
            },

            "semester": {
                "type": ["string", "null"]
            },

            "examination": {
                "type": ["string", "null"]
            },

            "date": {
                "type": ["string", "null"]
            }

        },

        "required": [

            "student_name",
            "register_number",
            "roll_number",
            "subject",
            "course",
            "semester",
            "examination",
            "date"

        ],

        "additionalProperties": False
    }

    # =========================================================
    # Answer Schema
    # =========================================================

    ANSWER_SCHEMA = {

        "type": "object",

        "properties": {

            "answer_number": {

                "type": [
                    "integer",
                    "string",
                    "null"
                ]

            },

            "answer_text": {

                "type": "string"

            },

            "continues_to_next_page": {

                "type": "boolean"

            },

            "source_page": {

                "type": "integer"

            }

        },

        "required": [

            "answer_number",
            "answer_text",
            "continues_to_next_page",
            "source_page"

        ],

        "additionalProperties": False
    }

    # =========================================================
    # Page Schema
    # =========================================================

    PAGE_SCHEMA = {

        "type": "object",

        "properties": {

            "page_number": {

                "type": "integer"

            },

            "page_type": {

                "type": "string",

                "enum": [

                    "COVER",
                    "ANSWER"

                ]

            },

            "student": STUDENT_SCHEMA,

            "answers": {

                "type": "array",

                "items": ANSWER_SCHEMA

            }

        },

        "required": [

            "page_number",
            "page_type"

        ],

        "additionalProperties": False
    }

    # =========================================================
    # Document Schema
    # =========================================================

    DOCUMENT_SCHEMA = {

        "type": "object",

        "properties": {

            "document": {

                "type": "object",

                "properties": {

                    "pdf_path": {
                        "type": "string"
                    },

                    "total_pages": {
                        "type": "integer"
                    },

                    "cover_page": {
                        "type": [
                            "integer",
                            "null"
                        ]
                    },

                    "answer_pages": {

                        "type": "array",

                        "items": {
                            "type": "integer"
                        }

                    }

                },

                "required": [

                    "pdf_path",
                    "total_pages",
                    "cover_page",
                    "answer_pages"

                ],

                "additionalProperties": False
            },

            "student": STUDENT_SCHEMA,

            "pages": {

                "type": "array",

                "items": PAGE_SCHEMA

            }

        },

        "required": [

            "document",
            "student",
            "pages"

        ],

        "additionalProperties": False
    }

    # =========================================================
    # Get Complete Schema
    # =========================================================

    @classmethod
    def get_schema(cls):

        """
        Return the complete OCR JSON schema.
        """

        return cls.DOCUMENT_SCHEMA